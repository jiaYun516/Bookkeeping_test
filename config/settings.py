    if DEBUG:
        # 僅供本機除錯使用的假金鑰，不具任何安全性
        SECRET_KEY = "django-insecure-dev-only"
    else:
        # 正式環境沒設金鑰就直接報錯，避免用不安全的值悄悄上線
        raise RuntimeError("未設定環境變數 DJANGO_SECRET_KEY")

